-- 3. Pompa dan jam operasi
create table if not exists pompa (
  kode        text primary key check (kode ~ '^[A-Z0-9-]+$'),
  no_urut     int  not null default 0,
  unit        text not null,              -- 'IPAB I', 'IPAL I', 'Tangki Timbun'
  nama        text not null,
  lokasi      text,
  daya_kw     numeric check (daya_kw >= 0),
  kapasitas   text,                       -- teks bebas: '230 m3/jam', '29,14 kgO2/jam'
  catatan     text,
  diubah_at   timestamptz not null default now()
);

create table if not exists jam_operasi_pompa (
  pompa_kode  text not null references pompa(kode) on delete cascade,
  tahun       int  not null check (tahun between 2020 and 2040),
  bulan       int  not null check (bulan between 1 and 12),
  jam         numeric check (jam >= 0),   -- tidak dibatasi jam per bulan: sumber memuat beberapa nilai di atasnya (lihat catatan pompa)
  keterangan  text,
  diubah_at   timestamptz not null default now(),
  primary key (pompa_kode, tahun, bulan)
);

alter table pompa enable row level security;
alter table jam_operasi_pompa enable row level security;
do $$
declare t text;
begin
  foreach t in array array['pompa', 'jam_operasi_pompa'] loop
    execute format('drop policy if exists baca on %I', t);
    execute format('create policy baca on %I for select to anon, authenticated using ((select peran_sesi()) is not null)', t);
    execute format('drop policy if exists tambah on %I', t);
    execute format('create policy tambah on %I for insert to anon, authenticated with check ((select peran_sesi()) = any (''{admin,tim_kinra}''::text[]))', t);
    execute format('drop policy if exists ubah on %I', t);
    execute format('create policy ubah on %I for update to anon, authenticated using ((select peran_sesi()) = any (''{admin,tim_kinra}''::text[])) with check ((select peran_sesi()) = any (''{admin,tim_kinra}''::text[]))', t);
    execute format('drop policy if exists hapus on %I', t);
    execute format('create policy hapus on %I for delete to anon, authenticated using ((select peran_sesi()) = ''admin'')', t);
  end loop;
end $$;

